func writeStructFields(b *bytes.Buffer, fields []Field) {
	for _, f := range fields {
		fmt.Fprintf(b, "\t%s %s\n", f.GoName, f.GoType)
	}
}

func writeFieldEmits(b *bytes.Buffer, fields []Field) {
	for _, f := range fields {
		writeFieldEmit(b, f)
	}
}

func writeFieldEmit(b *bytes.Buffer, f Field) {
	j := f.JSONName
	x := "x." + f.GoName
	switch f.Kind {
	case KindString:
		if f.Required {
			fmt.Fprintf(b, "\tb.String(%q, %s)\n", j, x)
		} else {
			fmt.Fprintf(b, "\tb.OptString(%q, %s)\n", j, x)
		}
	case KindEnum:
		if f.Required {
			fmt.Fprintf(b, "\tb.String(%q, string(%s))\n", j, x)
		} else {
			fmt.Fprintf(b, "\tb.OptString(%q, string(%s))\n", j, x)
		}
	case KindBool:
		if f.Required {
			fmt.Fprintf(b, "\tb.Bool(%q, %s)\n", j, x)
		} else {
			fmt.Fprintf(b, "\tb.OptBool(%q, %s)\n", j, x)
		}
	case KindInt:
		if f.Required {
			fmt.Fprintf(b, "\tb.Int(%q, %s)\n", j, x)
		} else {
			fmt.Fprintf(b, "\tb.OptInt(%q, %s)\n", j, x)
		}
	case KindFloat:
		if f.Required {
			fmt.Fprintf(b, "\tb.Float(%q, %s)\n", j, x)
		} else {
			fmt.Fprintf(b, "\tb.OptFloat(%q, %s)\n", j, x)
		}
	case KindStringSlice:
		fmt.Fprintf(b, "\tb.StrArray(%q, %s)\n", j, x)
	case KindNavSingle:
		fmt.Fprintf(b, "\tif %s != \"\" {\n\t\tb.Ref(%q, string(%s))\n\t}\n", x, j, x)
	case KindNavSlice:
		fmt.Fprintf(b, "\tif len(%s) > 0 {\n\t\tb.RefArray(%q, odata.Strings(%s))\n\t}\n", x, j, x)
	case KindComplex:
		writeComplexEmit(b, f, j, x)
	}
}

func writeComplexEmit(b *bytes.Buffer, f Field, j, x string) {
	switch {
	case strings.HasPrefix(f.GoType, "[]"):
		fmt.Fprintf(b, "\tif %s != nil {\n", x)
		fmt.Fprintf(b, "\t\titems := make([][]byte, len(%s))\n", x)
		fmt.Fprintf(b, "\t\tfor i := range %s {\n\t\t\titems[i] = %s[i].Bytes()\n\t\t}\n", x, x)
		fmt.Fprintf(b, "\t\tb.RawArray(%q, items)\n\t}\n", j)
	case strings.HasPrefix(f.GoType, "*"):
		fmt.Fprintf(b, "\tif %s != nil {\n\t\tb.Raw(%q, %s.Bytes())\n\t}\n", x, j, x)
	default:
		fmt.Fprintf(b, "\tb.Raw(%q, %s.Bytes())\n", j, x)
	}
}

// canonicalURI returns the preferred (non-trailing-slash) URI for a resource.
func canonicalURI(uris []string) string {
	for _, u := range uris {
		if !strings.HasSuffix(u, "/") || u == "/" {
			return u
		}
	}
	if len(uris) > 0 {
		return strings.TrimRight(uris[0], "/")
	}
	return ""
}

// wildcards extracts ServeMux path-parameter names ({Name}) from a URI, in
// order, ignoring the {$} end-of-path anchor.
func wildcards(uri string) []string {
	var names []string
	for {
		i := strings.IndexByte(uri, '{')
		if i < 0 {
			break
		}
		j := strings.IndexByte(uri[i:], '}')
		if j < 0 {
			break
		}
		name := uri[i+1 : i+j]
		if name != "$" {
			names = append(names, name)
		}
		uri = uri[i+j+1:]
	}
	return names
}

// anyWildcards reports whether any of the resource's URIs carries a path
// parameter. Such resources receive a server.Params argument so each route can
// supply its own parameters; this correctly handles resource types served under
// multiple parents with differing segment names.
func anyWildcards(uris []string) bool {
	for _, u := range uris {
		if len(wildcards(u)) > 0 {
			return true
		}
	}
	return false
}

// providerArgs renders the path-parameter portion of a provider method
// signature: ", p server.Params" when the resource is parameterized, else "".
func providerArgs(hasParams bool) string {
	if hasParams {
		return ", p server.Params"
	}
	return ""
}

// callArgs renders the path-parameter argument passed to a provider call: ", prm"
// when parameterized, else "".
func callArgs(hasParams bool) string {
	if hasParams {
		return ", prm"
	}
	return ""
}

// paramsLiteral renders a server.Params literal populated from a URI's
// wildcards, e.g. `server.Params{"ChassisId": r.PathValue("ChassisId")}`.
func paramsLiteral(uri string) string {
	wc := wildcards(uri)
	var b strings.Builder
	b.WriteString("server.Params{")
	for i, name := range wc {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "%q: r.PathValue(%q)", name, name)
	}
	b.WriteString("}")
	return b.String()
}

// writeRoutes registers each URI for method against the handler hVar. When the
// resource is parameterized, hVar takes (w, r, server.Params) and each route
// supplies its own parameters; otherwise hVar takes (w, r).
func writeRoutes(b *bytes.Buffer, method string, uris []string, hVar string, hasParams bool) {
	for _, uri := range uris {
		route := method + " " + pattern(uri)
		if !hasParams {
			fmt.Fprintf(b, "\tmux.HandleFunc(%q, %s)\n", route, hVar)
			continue
		}
		fmt.Fprintf(b, "\tmux.HandleFunc(%q, func(w http.ResponseWriter, r *http.Request) {\n", route)
		fmt.Fprintf(b, "\t\t%s(w, r, %s)\n\t})\n", hVar, paramsLiteral(uri))
	}
}

// pattern converts a Redfish URI into a net/http ServeMux pattern, anchoring
// trailing-slash variants with {$} so they match exactly rather than as a
// subtree.
func pattern(uri string) string {
	if len(uri) > 1 && strings.HasSuffix(uri, "/") {
		return uri + "{$}"
	}
	return uri
}

func oneLine(s string) string {
	s = strings.ReplaceAll(s, "\n", " ")
	if i := strings.Index(s, ".  "); i > 0 {
		return s[:i+1]
	}
	return s
}

// spaceWords inserts spaces before internal capital letters: "ComputerSystem"
// -> "Computer System".
func spaceWords(s string) string {
	var b strings.Builder
	for i, r := range s {
		if i > 0 && r >= 'A' && r <= 'Z' {
			b.WriteByte(' ')
		}
		b.WriteRune(r)
	}
	return b.String()
}
